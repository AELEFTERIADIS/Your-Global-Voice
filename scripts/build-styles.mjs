import { readFile, writeFile } from 'node:fs/promises';
export const stylesheetNames = ['styles.css', 'mission.css', 'about.css', 'contact.css', 'donate.css'];
export function resolveMedia(condition, properties) {
 return condition.replace(/\{(--[a-z0-9-]+)\}/g, (_, name) => {
  if (!properties[name]) throw new Error(`Unknown breakpoint token ${name}`);
  return properties[name];
 });
}
export async function compileStyles() {
 const { properties, media } = JSON.parse(await readFile(new URL('../styles/tokens.json', import.meta.url), 'utf8'));
 const root = ':root {\n' + Object.entries(properties).map(([name, value]) => `  ${name}: ${value};`).join('\n') + '\n}\n';
 const files = new Map();
 for (const file of stylesheetNames) {
  const source = await readFile(new URL(`../styles/${file}`, import.meta.url), 'utf8');
  const compiled = source.replace(/@media\s+\(--([a-z0-9-]+)\)/g, (_, name) => {
   if (!media[name]) throw new Error(`Unknown media condition ${name} in ${file}`);
   return `@media ${resolveMedia(media[name], properties)}`;
  });
  if (/@media\s+\(--/.test(compiled)) throw new Error(`Unexpanded media condition in ${file}`);
  files.set(file, '/* Generated by scripts/build-styles.mjs; edit styles/' + file + '. */\n' + (file === 'styles.css' ? root : '') + compiled);
 }
 return files;
}
export async function buildStyles() {
 for (const [file, text] of await compileStyles()) await writeFile(new URL(`../public/${file}`, import.meta.url), text);
}
